"""Compact controls on real disposable workerd families."""
from pathlib import Path
import sys
import pytest
from test_runtime import runtime, state
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tests'))
from parent_pin_ui import open_parent, check_pin_spacing


@pytest.mark.parametrize('width', [390, 1280])
def test_compact_names_pin_and_awake(runtime, width):
    from playwright.sync_api import sync_playwright, expect
    with sync_playwright() as pw, pw.chromium.launch(executable_path='/usr/bin/chromium', args=['--no-sandbox']) as browser:
        context = browser.new_context(viewport={'width': width, 'height': 844}, reduced_motion='reduce', service_workers='block')
        context.add_init_script((Path(__file__).resolve().parents[1] / 'tests/fixtures/wake_lock.js').read_text())
        page = context.new_page()
        page.goto(runtime.origin)
        page.locator('#tryGuestBank').click()
        page.locator('#tourSkip').click()
        open_parent(page)
        expect(page.locator('#parentLabel')).not_to_be_visible()
        expect(page.locator('#parentNameValue')).to_have_text('Dad')
        page.locator('#editParentName').click()
        expect(page.locator('#parentLabel')).to_be_focused()
        page.locator('#parentLabel').fill('Unsaved Mom')
        page.locator('#cancelParentName').focus()
        page.evaluate('backgroundRefresh()')
        expect(page.locator('#parentLabel')).to_have_value('Unsaved Mom')
        page.locator('#cancelParentName').click()
        expect(page.locator('#parentNameValue')).to_have_text('Dad')
        page.locator('#editParentName').click()
        page.locator('#parentLabel').fill('Cancel with Escape')
        page.keyboard.press('Escape')
        expect(page.locator('#parentLabel')).not_to_be_visible()
        page.locator('#editParentName').click()
        page.locator('#parentLabel').fill("Mom & <Dad>")
        page.keyboard.press('Enter')
        expect(page.locator('#parentNameValue')).to_have_text('Mom & <Dad>')
        expect(page.locator('#parentLabel')).not_to_be_visible()
        assert page.locator('#parentNameValue > *').count() == 0
        # Kid names stay labels; editing/removal retain the existing guarded dialogs.
        expect(page.locator('#kidName')).not_to_be_visible()
        row = page.locator('.dk').first
        for selector in ('.rename-kid', '.remove-kid'):
            assert row.locator(selector).bounding_box()['height'] >= 44
        row.locator('.rename-kid').click()
        expect(page.locator('#kidName')).to_be_focused()
        page.locator('#kidName').fill('Not saved')
        page.keyboard.press('Escape')
        expect(row.locator('.dk-head')).to_contain_text('Sample Kid')
        row.locator('.rename-kid').click()
        page.locator('#kidName').fill('Alex & <Sam>')
        page.keyboard.press('Enter')
        expect(page.locator('.dk-head')).to_contain_text('Alex & <Sam>')
        page.locator('.remove-kid').click()
        expect(page.locator('#kidDialogTitle')).to_have_text('Remove Alex & <Sam>?')
        expect(page.locator('#kidDialogCancel')).to_be_focused()
        page.locator('#kidDialogCancel').click()
        expect(page.locator('.dk')).to_have_count(1)
        # All PIN modes share the focused-input/keypad separation.
        page.locator('#changePinBtn').click()
        check_pin_spacing(page)
        page.locator('#parentPinInput').fill('4321')
        page.locator('.pin-card [data-k="ok"]').click()
        check_pin_spacing(page)
        page.locator('.pin-card .close').click()
        toggle = page.locator('#keepAwake')
        expect(page.locator('#awakeStatus')).not_to_be_visible()
        page.evaluate('__wake.mode = "auto"')
        toggle.check()
        page.wait_for_function('__wake.locks.some(lock => !lock.released)')
        expect(page.locator('#awakeStatus')).not_to_be_visible()
        toggle.uncheck()
        expect(page.locator('#awakeStatus')).not_to_be_visible()
        page.evaluate('__wake.mode = "deny"')
        toggle.check()
        expect(page.locator('#awakeStatus')).to_contain_text('declined')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.reload()
        open_parent(page)
        expect(page.locator('#parentNameValue')).to_have_text('Mom & <Dad>')
        expect(page.locator('.dk-head')).to_contain_text('Alex & <Sam>')
        context.close()
        unsupported = browser.new_context(viewport={'width': width, 'height': 844}, service_workers='block')
        unsupported.add_init_script('Object.defineProperty(navigator, "wakeLock", {value: undefined})')
        page = unsupported.new_page()
        page.goto(runtime.origin)
        page.locator('#tryGuestBank').click()
        page.locator('#tourSkip').click()
        open_parent(page)
        expect(page.locator('#keepAwake')).to_be_disabled()
        expect(page.locator('#awakeStatus')).to_contain_text('does not support')
        expect(page.locator('#parentNameValue')).to_have_text('Dad')
        expect(page.locator('.dk-head')).to_contain_text('Sample Kid')
        unsupported.close()
